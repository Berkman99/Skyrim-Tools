using NpcFaceManager.Core.Environment;

namespace NpcFaceManager.Tests;

public sealed class EnvironmentTests : IDisposable
{
    private readonly string _dir = Directory.CreateTempSubdirectory("nfm-tests-").FullName;

    public void Dispose() => Directory.Delete(_dir, true);

    [Theory]
    [InlineData(@"@ByteArray(Default)", "Default")]
    [InlineData(@"@ByteArray(D:\\Games\\Skyrim Special Edition)", @"D:\Games\Skyrim Special Edition")]
    [InlineData("\"quoted value\"", "quoted value")]
    [InlineData("plain", "plain")]
    public void Unquote_HandlesQtFormats(string raw, string expected) => Assert.Equal(expected, IniFile.Unquote(raw));

    [Fact]
    public void Mo2Instance_UsesDefaultsAndBaseDir()
    {
        File.WriteAllText(Path.Combine(_dir, "ModOrganizer.ini"), """
            [General]
            gamePath=@ByteArray(C:\\Steam\\Skyrim Special Edition)
            selected_profile=@ByteArray(My Profile)

            [Settings]
            mod_directory=%BASE_DIR%/custom mods
            """);

        var instance = Mo2Instance.Load(Path.Combine(_dir, "ModOrganizer.ini"));

        Assert.Equal(_dir, instance.BaseDirectory);
        Assert.Equal(Path.Combine(_dir, "custom mods"), instance.ModsDirectory);
        Assert.Equal(Path.Combine(_dir, "profiles"), instance.ProfilesDirectory);
        Assert.Equal(@"C:\Steam\Skyrim Special Edition", instance.GamePath);
        Assert.Equal("My Profile", instance.SelectedProfile);
    }

    [Fact]
    public void ReadModList_KeepsOrderAndStates()
    {
        File.WriteAllLines(Path.Combine(_dir, "modlist.txt"),
        [
            "# This file was automatically generated by Mod Organizer.",
            "+Top Mod",
            "-Disabled Mod",
            "+Faces_separator",
            "*DLC: Dawnguard",
        ]);

        var list = ProfileFiles.ReadModList(_dir);

        Assert.Equal(4, list.Count);
        Assert.Equal(("Top Mod", ModListState.Enabled), (list[0].Name, list[0].State));
        Assert.Equal(ModListState.Disabled, list[1].State);
        Assert.True(list[2].IsSeparator);
        Assert.Equal(ModListState.Unmanaged, list[3].State);
    }

    [Fact]
    public void ApplyMergeResult_DisablesOverhaulsAndEnablesOutput()
    {
        File.WriteAllLines(Path.Combine(_dir, "modlist.txt"), ["# header", "+Hair Pack", "+Overhaul A", "+Overhaul B"]);
        File.WriteAllLines(Path.Combine(_dir, "plugins.txt"), ["# header", "*HairPack.esp", "*OverhaulA.esp", "*OverhaulB.esp"]);

        ProfileFiles.ApplyMergeResult(_dir, new MergeChanges(["Overhaul A", "Overhaul B"], ["OverhaulA.esp", "OverhaulB.esp"], [], [], "Merged Faces", "Merged.esp"));

        var mods = File.ReadAllLines(Path.Combine(_dir, "modlist.txt"));
        Assert.Equal(["# header", "+Merged Faces", "+Hair Pack", "-Overhaul A", "-Overhaul B"], mods);
        var plugins = File.ReadAllLines(Path.Combine(_dir, "plugins.txt"));
        Assert.Equal(["# header", "*HairPack.esp", "OverhaulA.esp", "OverhaulB.esp", "*Merged.esp"], plugins);
        Assert.NotEmpty(Directory.GetFiles(_dir, "modlist.txt.NAM *"));
    }

    [Fact]
    public void ApplyMergeResult_RunTwice_DoesNotDuplicateOutput()
    {
        File.WriteAllLines(Path.Combine(_dir, "modlist.txt"), ["+Overhaul A"]);
        File.WriteAllLines(Path.Combine(_dir, "plugins.txt"), ["*OverhaulA.esp"]);

        ProfileFiles.ApplyMergeResult(_dir, new MergeChanges(["Overhaul A"], ["OverhaulA.esp"], [], [], "Merged Faces", "Merged.esp"));
        ProfileFiles.ApplyMergeResult(_dir, new MergeChanges(["Overhaul A"], ["OverhaulA.esp"], [], [], "Merged Faces", "Merged.esp"));

        Assert.Single(File.ReadAllLines(Path.Combine(_dir, "modlist.txt")), l => l == "+Merged Faces");
        Assert.Single(File.ReadAllLines(Path.Combine(_dir, "plugins.txt")), l => l == "*Merged.esp");
    }
}


